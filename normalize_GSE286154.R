args <- commandArgs(trailingOnly=TRUE)
stopifnot(length(args)==1)
base <- args[1]; out <- file.path(base,'results')
suppressPackageStartupMessages(library(DESeq2))
d <- read.delim(file.path(base,'GSE286154_gene_count.txt'),check.names=FALSE,stringsAsFactors=FALSE)
stopifnot(names(d)[1]=='gene',!anyDuplicated(d$gene),all(nzchar(d$gene)))
x <- as.matrix(d[,-1]);rownames(x)<-d$gene
stopifnot(is.numeric(x),all(is.finite(x)),all(x>=0),all(x==floor(x)),max(x)<.Machine$integer.max,all(colSums(x)>0),sum(rowSums(x>0)==ncol(x))>0)
storage.mode(x)<-'integer'
meta<-read.csv(file.path(out,'GSE286154_metadata.csv'),row.names=1,check.names=FALSE)
stopifnot(identical(rownames(meta),colnames(x)))
dds<-DESeqDataSetFromMatrix(countData=x,colData=meta,design=~1)
dds<-estimateSizeFactors(dds,type='ratio')
norm<-counts(dds,normalized=TRUE)
stopifnot(identical(counts(dds),x),all(is.finite(norm)),all(sizeFactors(dds)>0),isTRUE(all.equal(unname(norm),unname(sweep(x,2,sizeFactors(dds),'/')),tolerance=1e-12)))
write.table(data.frame(gene_id=rownames(norm),norm,check.names=FALSE),file.path(out,'GSE286154_normalized_expression.tsv'),sep='\t',quote=FALSE,row.names=FALSE)
saveRDS(dds,file.path(out,'GSE286154_DESeq2_sizefactor_only.rds'))
write.csv(data.frame(sample_id=colnames(x),size_factor=sizeFactors(dds),raw_library_size=colSums(x),normalized_column_sum=colSums(norm)),file.path(out,'GSE286154_size_factors.csv'),row.names=FALSE)
capture.output(sessionInfo(),file=file.path(out,'R_sessionInfo.txt'))
cat('\nNORMALIZATION COMPLETE. DESeq2 default ratio size factors, design ~1. No dispersion estimation, model fitting or DE testing.\nSize-factor range: ',range(sizeFactors(dds)),'\nNormalized expression range: ',range(norm),'\nRaw counts preserved in object: TRUE\n',file=file.path(out,'GSE286154_QC_report.txt'),append=TRUE)
print(sizeFactors(dds));print(dim(norm))
